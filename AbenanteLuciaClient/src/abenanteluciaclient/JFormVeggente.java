    //legge la domanda, la mostra nella chat e la invia al server.
    // Se il campo è vuoto non fa niente.
    private void btnDomandaActionPerformed(java.awt.event.ActionEvent evt) {
        String domanda = txtFldDomanda.getText().trim();
        if (domanda.isEmpty()) {
            return;
        }
        aggiungiChat("Tu: " + domanda);
        connessione.domanda(domanda);
        txtFldDomanda.setText(""); // svuota il campo per la prossima domanda

    }
